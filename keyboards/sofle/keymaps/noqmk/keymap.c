bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    switch (keycode) {
        case KC_QWERTY:
            if (record->event.pressed) {
                set_single_persistent_default_layer(_QWERTY);
            }
            return false;
        case KC_LOWER:
            if (record->event.pressed) {
                layer_on(_LOWER);
                update_tri_layer(_LOWER, _RAISE, _ADJUST);
            } else {
                layer_off(_LOWER);
                update_tri_layer(_LOWER, _RAISE, _ADJUST);
            }
            return false;
        case KC_RAISE:
            if (record->event.pressed) {
                layer_on(_RAISE);
                update_tri_layer(_LOWER, _RAISE, _ADJUST);
            } else {
                layer_off(_RAISE);
                update_tri_layer(_LOWER, _RAISE, _ADJUST);
            }
            return false;
        case KC_ADJUST:
            if (record->event.pressed) {
                layer_on(_ADJUST);
            } else {
                layer_off(_ADJUST);
            }
            return false;
        case KC_PRVWD:
            if (record->event.pressed) {
                if (keymap_config.swap_lctl_lgui) {
                    register_mods(mod_config(MOD_LALT));
                    register_code(KC_LEFT);
                } else {
                    register_mods(mod_config(MOD_LCTL));
                    register_code(KC_LEFT);
                }
            } else {
                if (keymap_config.swap_lctl_lgui) {
                    unregister_mods(mod_config(MOD_LALT));
                    unregister_code(KC_LEFT);
                } else {
                    unregister_mods(mod_config(MOD_LCTL));
                    unregister_code(KC_LEFT);
                }
            }
            break;
        case KC_NXTWD:
             if (record->event.pressed) {
                if (keymap_config.swap_lctl_lgui) {
                    register_mods(mod_config(MOD_LALT));
                    register_code(KC_RIGHT);
                } else {
                    register_mods(mod_config(MOD_LCTL));
                    register_code(KC_RIGHT);
                }
            } else {
                if (keymap_config.swap_lctl_lgui) {
                    unregister_mods(mod_config(MOD_LALT));
                    unregister_code(KC_RIGHT);
                } else {
                    unregister_mods(mod_config(MOD_LCTL));
                    unregister_code(KC_RIGHT);
                }
            }
            break;
        case KC_LSTRT:
            if (record->event.pressed) {
                if (keymap_config.swap_lctl_lgui) {
                     //CMD-arrow on Mac, but we have CTL and GUI swapped
                    register_mods(mod_config(MOD_LCTL));
                    register_code(KC_LEFT);
                } else {
                    register_code(KC_HOME);
                }
            } else {
                if (keymap_config.swap_lctl_lgui) {
                    unregister_mods(mod_config(MOD_LCTL));
                    unregister_code(KC_LEFT);
                } else {
                    unregister_code(KC_HOME);
                }
            }
            break;
        case KC_LEND:
            if (record->event.pressed) {
                if (keymap_config.swap_lctl_lgui) {
                    //CMD-arrow on Mac, but we have CTL and GUI swapped
                    register_mods(mod_config(MOD_LCTL));
                    register_code(KC_RIGHT);
                } else {
                    register_code(KC_END);
                }
            } else {
                if (keymap_config.swap_lctl_lgui) {
                    unregister_mods(mod_config(MOD_LCTL));
                    unregister_code(KC_RIGHT);
                } else {
                    unregister_code(KC_END);
                }
            }
            break;
        case KC_DLINE:
            if (record->event.pressed) {
                register_mods(mod_config(MOD_RCTL));
                register_code(KC_BSPC);
            } else {
                unregister_mods(mod_config(MOD_LCTL));
                unregister_code(KC_BSPC);
            }
            break;
        case KC_COPY:
            if (record->event.pressed) {
                // Swap CTL and GUI on Mac
                if (keymap_config.swap_lctl_lgui) {
                    register_mods(mod_config(MOD_MASK_GUI));
                    register_code(KC_C);
                }
                // Linux/Windows
                else {
                    register_mods(mod_config(MOD_MASK_CS));
                    register_code(KC_C);
                }

            } else {
                if (keymap_config.swap_lctl_lgui) {
                    unregister_mods(mod_config(MOD_MASK_GUI));
                    unregister_code(KC_C);
                } else {
                    unregister_mods(mod_config(MOD_MASK_CS));
                    unregister_code(KC_C);
                }
            }
            break;
        case KC_PASTE:
            if (record->event.pressed) {
                if (keymap_config.swap_lctl_lgui) {
                    register_mods(mod_config(MOD_MASK_GUI));
                    register_code(KC_V);
                } else {
                    register_mods(mod_config(MOD_MASK_CS));
                    register_code(KC_V);
                }
            } else {
                if (keymap_config.swap_lctl_lgui) {
                    unregister_mods(mod_config(MOD_MASK_GUI));
                    unregister_code(KC_V);
                } else {
                    unregister_mods(mod_config(MOD_MASK_CS));
                    unregister_code(KC_V);
                }
            }
            break;
        case KC_CUT:
            if (record->event.pressed) {
                if (keymap_config.swap_lctl_lgui) {
                    register_mods(mod_config(MOD_MASK_GUI));
                    register_code(KC_X);
                } else {
                    register_mods(mod_config(MOD_MASK_CS));
                    register_code(KC_X);
                }
            } else {
                if (keymap_config.swap_lctl_lgui) {
                    unregister_mods(mod_config(MOD_MASK_GUI));
                    unregister_code(KC_X);
                } else {
                    unregister_mods(mod_config(MOD_MASK_CS));
                    unregister_code(KC_X);
                }
            }
            break;
        case KC_UNDO:
            if (record->event.pressed) {
                if (keymap_config.swap_lctl_lgui) {
                    register_mods(mod_config(MOD_MASK_GUI));
                    register_code(KC_Z);
                } else {
                    register_mods(mod_config(MOD_MASK_CS));
                    register_code(KC_Z);
                }
            } else {
                if (keymap_config.swap_lctl_lgui) {
                    unregister_mods(mod_config(MOD_MASK_GUI));
                    unregister_code(KC_Z);
                } else {
                    unregister_mods(mod_config(MOD_MASK_CS));
                    unregister_code(KC_Z);
                }
            }
            break;
        case KC_CREATE:
            if (record->event.pressed) {
                if (keymap_config.swap_lctl_lgui) {
                    register_mods(mod_config(MOD_LCTL));
                    register_code(KC_N);
                } else {
                    register_mods(MOD_BIT(KC_LALT));
                    register_code(KC_INS);
                }
            } else {
                if (keymap_config.swap_lctl_lgui) {
                    unregister_code(KC_N);
                    unregister_mods(mod_config(MOD_LCTL));
                } else {
                    unregister_code(KC_INS);
                    unregister_mods(MOD_BIT(KC_LALT));
                }
            }
            break;
        case KC_SCREENSHOT:
            if (record->event.pressed) {
                if (keymap_config.swap_lctl_lgui) {
                    register_mods(mod_config(MOD_MASK_CSG));
                    register_code(KC_4);
                } else {
                    register_code(KC_PSCR);
                }
            } else {
                if (keymap_config.swap_lctl_lgui) {
                    register_code(KC_4);
                    unregister_mods(mod_config(MOD_MASK_CSG));
                } else {
                    unregister_code(KC_PSCR);
                }
            }
            break;
        case KC_NEWTAB:
            // combine key for new terminal tab in linux and mac
            // CTRL + SHIFT + T for linux
            // CMD + T for mac
            if (keymap_config.swap_lctl_lgui) {
                if (record->event.pressed) {
                    register_mods(mod_config(MOD_LCTL));
                    register_code(KC_T);
                } else {
                    unregister_code(KC_T);
                    unregister_mods(mod_config(MOD_LCTL));
                }
            } else {
                if (record->event.pressed) {
                    register_mods(mod_config(MOD_MASK_CS));
                    register_code(KC_T);
                } else {
                    unregister_code(KC_T);
                    unregister_mods(mod_config(MOD_MASK_CS));
                }
            }
            break;
        case KC_SW:
            // to switch window in linux and mac
            // ALT + TAB for linux
            // CMD + TAB for mac
            if (record->event.pressed) {
                if (keymap_config.swap_lctl_lgui) {
                    register_mods(mod_config(MOD_LCTL));
                    register_code(KC_TAB);
                } else {
                    register_mods(mod_config(MOD_MASK_ALT));
                    register_code(KC_TAB);
                }
            } else {
                if (keymap_config.swap_lctl_lgui) {
                    unregister_code(KC_TAB);
                    unregister_mods(mod_config(MOD_LCTL));
                } else {
                    unregister_code(KC_TAB);
                    unregister_mods(mod_config(MOD_MASK_ALT));
                }
            }
            break;
        case KC_TAB1:
        case KC_TAB2:
        case KC_TAB3:
        case KC_TAB4:
        case KC_TAB5:
        case KC_TAB6:
        case KC_TAB7:
        case KC_TAB8:
        case KC_TAB9:
            // to switch to a specific tab in linux and mac
            // ALT + 1 to ALT + 9 for linux
            // CMD + 1 to CMD + 9 for mac
            if (record->event.pressed) {
                if (keymap_config.swap_lctl_lgui) {
                    register_mods(mod_config(MOD_LCTL));
                    register_code(KC_1 + (keycode - KC_TAB1));
                } else {
                    register_mods(mod_config(MOD_MASK_ALT));
                    register_code(KC_1 + (keycode - KC_TAB1));
                }
            } else {
                if (keymap_config.swap_lctl_lgui) {
                    unregister_code(KC_1 + (keycode - KC_TAB1));
                    unregister_mods(mod_config(MOD_LCTL));
                } else {
                    unregister_code(KC_1 + (keycode - KC_TAB1));
                    unregister_mods(mod_config(MOD_MASK_ALT));
                }
            }
            break;
    }

    /* This stops any keypress to be sent to the computer when the keyboard is locked */
    return true;
}

